function iconMarkup(name) {
  const path = SOCIAL_ICONS[name];
  if (!path) return null;
  return `<svg viewBox="0 0 24 24" width="20" height="20" aria-hidden="true" focusable="false"><path d="${path}"/></svg>`;
}

/**
 * Turn the footer's Facebook/Twitter/Instagram text links into square icon
 * buttons (matching the source: 48x48 light-grey buttons with a dark glyph).
 * Marks the containing list with .footer-social so the CSS can style it.
 */
function decorateSocial(footer) {
  footer.querySelectorAll('a').forEach((a) => {
    const key = a.textContent.trim().toLowerCase();
    const svg = iconMarkup(key);
    if (!svg) return;
    a.setAttribute('aria-label', a.textContent.trim());
    a.setAttribute('title', a.textContent.trim());
    a.innerHTML = svg;
    a.classList.add('footer-social-link');
    const list = a.closest('ul');
    if (list) list.classList.add('footer-social');
  });
}

/**
 * loads and decorates the footer
 * @param {Element} block The footer block element
 */
export default async function decorate(block) {
  // load footer as fragment
  // metadata-independent dual-path: /content/footer (localhost/aem up) then /footer (DA/EDS prod)
  const footerMeta = getMetadata('footer');
  const footerPath = footerMeta ? new URL(footerMeta, window.location).pathname : '/content/footer';
  const fragment = (await loadFragment(footerPath)) || (await loadFragment('/footer'));

  // decorate footer DOM
  block.textContent = '';
  const footer = document.createElement('div');
  while (fragment.firstElementChild) footer.append(fragment.firstElementChild);

  decorateSocial(footer);

  block.append(footer);
}
